export function generate(headerPath = "data/x2.exe.h"): string {
  const text = readFileSync(headerPath, "latin1");
  const out: string[] = [
    "// GENERATED by tools/gen-d3d9-enums.ts from data/x2.exe.h (the enum values IDA recovered from x2.exe). Do not edit.",
    "",
  ];
  for (const [ida, name, prefix] of GROUPS) {
    const m = new RegExp(`^enum ${ida} : __int32\\n\\{\\n([\\s\\S]*?)\\n\\};`, "m").exec(text);
    if (!m) throw new Error(`enum ${ida} not found in ${headerPath}`);
    const members: [string, number][] = [];
    for (const line of m[1]!.split("\n")) {
      const mm = /^\s*(\w+) = (0x[0-9A-Fa-f]+|-?\d+),?$/.exec(line);
      if (!mm) throw new Error(`${ida}: cannot parse ${JSON.stringify(line)}`);
      if (!mm[1]!.startsWith(prefix)) throw new Error(`${ida}: member ${mm[1]} lacks prefix ${prefix}`);
      if (mm[1]!.endsWith("FORCE_DWORD")) continue;
      members.push([mm[1]!.slice(prefix.length), Number(mm[2]) >>> 0]);
    }
    out.push(`/** ${ida} */`, `export const ${name} = {`);
    for (const [k, v] of members) out.push(`  ${/^\d/.test(k) ? JSON.stringify(k) : k}: 0x${v.toString(16).toUpperCase()},`);
    out.push("} as const;", "");
  }
  return out.join("\n");
}

if (import.meta.main) {
  const target = "packages/d3d9/src/enums.generated.ts";
  const text = generate();
  if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== text) { console.error(`${target} is stale: run bun run tools/gen-d3d9-enums.ts`); process.exit(1); }
    console.log(`${target} is up to date`);
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${target} (${text.split("\n").length} lines)`);
  }
}
