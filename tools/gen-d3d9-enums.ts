/**
 * Generates packages/d3d9/src/enums.generated.ts from the enum definitions IDA recovered into data/x2.exe.h (so the numeric
 * values the TypeScript layer uses are the ones the client was compiled against; nothing is typed in from memory).
 * Only plain enums can come from here; the DWORD flag sets (#defines in d3d9types.h) live in packages/d3d9/src/enums.ts.
 * Run: bun run tools/gen-d3d9-enums.ts            (rewrites the file)
 *      bun run tools/gen-d3d9-enums.ts --check    (exit 1 if the committed file differs)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

/** IDA enum name -> [TS object name, member prefix to strip]. */
