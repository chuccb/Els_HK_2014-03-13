#!/usr/bin/env python3
"""
Generates packages/freetype/src/interp-tables.ts (Pop_Push_Count, opcode_length, Instruct_Dispatch) from FreeType 2.4.11's src/truetype/ttinterp.c, so the
256-entry tables of the port are copied by a program, not by hand:

    curl -sL https://codeload.github.com/freetype/freetype/tar.gz/refs/tags/VER-2-4-11 | tar xz -C /tmp/ftsrc
    python3 tools/gen-freetype-tables.py /tmp/ftsrc/freetype-VER-2-4-11/src/truetype/ttinterp.c
"""
import os, re, sys

src_path = sys.argv[1]
src = open(src_path, encoding="latin-1").read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)  # comments

i = src.index("const FT_Byte  Pop_Push_Count[256] =")
j = src.index("};", i)
packs = re.findall(r"PACK\(\s*(\d+),\s*(\d+)\s*\)", src[i:j])
assert len(packs) == 256, len(packs)
ppc = [(int(a) << 4) | int(b) for a, b in packs]

i = src.index("const FT_Char  opcode_length[256] =")
j = src.index("};", i)
body = src[i:j]
nums = [int(x) for x in re.findall(r"-?\d+", body[body.index("{") + 1:])]
assert len(nums) == 256, len(nums)

i = src.index("TInstruction_Function  Instruct_Dispatch[256] =")
j = src.index("};", i)
names = re.findall(r"Ins_([A-Za-z0-9_]+)", src[i:j])
assert len(names) == 256, len(names)


def rows(a, f):
    return ",\n  ".join(", ".join(f(v) for v in a[k:k + 16]) for k in range(0, len(a), 16))


out = [
    """// GENERATED by tools/gen-freetype-tables.py from FreeType 2.4.11 src/truetype/ttinterp.c: Pop_Push_Count, opcode_length and Instruct_Dispatch.
// Do not edit by hand.
import type { TtExec } from "./interp.ts";

/** Pop_Push_Count[256]: (values popped << 4) | values pushed */
export const POP_PUSH_COUNT = new Uint8Array([
  %s,
]);

/** opcode_length[256]: bytes of an instruction; negative = the next byte gives a count (NPUSHB: -1, NPUSHW: -2) */
export const OPCODE_LENGTH = new Int8Array([
  %s,
]);

/** Instruct_Dispatch[256] */
export function dispatch(x: TtExec, opcode: number, a: number): void {
  switch (opcode) {
"""
    % (rows(ppc, lambda v: "0x%02x" % v), rows(nums, str))
]
for k, n in enumerate(names):
    out.append("    case 0x%02x:\n      x.ins%s(a);\n      break;\n" % (k, n))
out.append("  }\n}\n")
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "packages", "freetype", "src", "interp-tables.ts")
open(dest, "w").write("".join(out))
print("wrote", dest)
