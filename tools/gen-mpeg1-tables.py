#!/usr/bin/env python3
"""
Generates packages/assets/src/mpeg1-tables.ts: the variable length code tables of ISO/IEC 11172-2 Annex B and the default intra matrix,
read from the array data of libavcodec's mpeg12data.c (codes and matrix values are facts of the standard; no code is copied).

    gh api -H "Accept: application/vnd.github.raw" repos/FFmpeg/FFmpeg/contents/libavcodec/mpeg12data.c > /home/user/work/scratch/ff/mpeg12data.c
    python3 tools/gen-mpeg1-tables.py [path/to/mpeg12data.c]

The macroblock_type tables (B.2) are typed in below.  packages/assets/test/mpeg1.test.ts checks the tables' structure, and the decoder
reproduces FFmpeg's pictures for the 30 shipped movies and the synthetic streams, which exercises every table.
"""
import os, re, sys
SRC = sys.argv[1] if len(sys.argv) > 1 else '/home/user/work/scratch/ff/mpeg12data.c'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'packages', 'assets', 'src', 'mpeg1-tables.ts')
src=open(SRC).read()
def arr(name, ctype_re=r'const [a-z0-9_ ]+'):
    m=re.search(name+r'\s*\[[^\]]*\](?:\[[^\]]*\])?\s*=\s*\{(.*?)\n\};', src, re.S)
    assert m, name
    return m.group(1)
def pairs(body):
    return [(int(a,16),int(b)) for a,b in re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*(\d+)\s*\}', body)]
def ints(body):
    body=re.sub(r'/\*.*?\*/','',body)
    return [int(x) for x in re.findall(r'-?\d+', body)]
def hexints(body):
    return [int(x,16) for x in re.findall(r'0x[0-9a-fA-F]+', body)]

rl=pairs(arr('ff_mpeg1_vlc_table'))
level=ints(arr('ff_mpeg12_level')); run=ints(arr('ff_mpeg12_run'))
assert len(level)==len(run)==111 and len(rl)==113, (len(level),len(run),len(rl))
rl_entries=[(rl[i][0],rl[i][1],run[i],level[i]) for i in range(111)]
esc=rl[111]; eob=rl[112]
assert esc==(1,6) and eob==(2,2)
mba=pairs(arr('ff_mpeg12_mbAddrIncrTable'))
cbp=pairs(arr('ff_mpeg12_mbPatTable'))
mv=pairs(arr('ff_mpeg12_mbMotionVectorTable'))
dcl_code=hexints(arr('ff_mpeg12_vlc_dc_lum_code')); dcl_bits=ints(arr('ff_mpeg12_vlc_dc_lum_bits'))
dcc_code=hexints(arr('ff_mpeg12_vlc_dc_chroma_code')); dcc_bits=ints(arr('ff_mpeg12_vlc_dc_chroma_bits'))
intra=ints(arr('ff_mpeg1_default_intra_matrix'))
assert len(mba)==36 and len(cbp)==64 and len(mv)==17 and len(dcl_code)==12 and len(intra)==64, (len(mba),len(cbp),len(mv),len(dcl_code),len(intra))

def fmt_pairs(p, per=6):
    out=[]
    for i in range(0,len(p),per):
        out.append('  '+' '.join('[0x%x, %d],'%(a,b) for a,b in p[i:i+per]))
    return '\n'.join(out)
def fmt_rl(e, per=3):
    out=[]
    for i in range(0,len(e),per):
        out.append('  '+' '.join('[0x%x, %d, %d, %d],'%t for t in e[i:i+per]))
    return '\n'.join(out)
def fmt_ints(a, per=16):
    return '\n'.join('  '+', '.join(str(x) for x in a[i:i+per])+',' for i in range(0,len(a),per))

ts=f'''/**
 * Tables of ISO/IEC 11172-2 (MPEG-1 video) Annex B: the variable length codes and the default quantiser matrix.  Every code is
 * `[code, bits]` (the code value right-aligned in `bits` bits).  GENERATED by tools/gen-mpeg1-tables.py from the array data of libavcodec's
 * `mpeg12data.c` (tables B.1, B.3, B.4, B.12 / B.13, B.14 and the default matrix: facts of the standard, no code copied); the macroblock_type
 * tables B.2 are typed in.  `mpeg1.test.ts` checks that every table is a prefix code, and the decoder reproduces FFmpeg's pictures for the
 * shipped movies (30 files, 18,514 pictures) and for synthetic streams that use every table.
 */

/** Table B.14 (DCT coefficients, table zero): [code, bits, run, level]; the sign bit `s` follows every code.  111 entries of the standard. */
export const RUN_LEVEL: ReadonlyArray<readonly [code: number, bits: number, run: number, level: number]> = [
{fmt_rl(rl_entries)}
];
/** `escape` (followed by 6 bits of run and an 8 or 16 bit level) and `end of block` */
export const RL_ESCAPE: readonly [number, number] = [0x{esc[0]:x}, {esc[1]}];
export const RL_EOB: readonly [number, number] = [0x{eob[0]:x}, {eob[1]}];

/** Table B.1 macroblock_address_increment: index = increment - 1 for 1..33; [33] = macroblock_escape (+33), [34] = macroblock_stuffing */
export const MB_ADDR_INCR: ReadonlyArray<readonly [code: number, bits: number]> = [
{fmt_pairs(mba[:35])}
];

/** Table B.3 coded_block_pattern, index = pattern (bit 5 = first luminance block ... bit 0 = Cr) */
export const CODED_BLOCK_PATTERN: ReadonlyArray<readonly [code: number, bits: number]> = [
{fmt_pairs(cbp)}
];

/** Table B.4 motion_code, index = |motion_code| 0..16 (a sign bit follows when it is not 0) */
export const MOTION_CODE: ReadonlyArray<readonly [code: number, bits: number]> = [
{fmt_pairs(mv)}
];

/** Tables B.12 / B.13: dct_dc_size_luminance / dct_dc_size_chrominance, index = size 0..11 */
export const DC_SIZE_LUMA: ReadonlyArray<readonly [code: number, bits: number]> = [
{fmt_pairs(list(zip(dcl_code,dcl_bits)))}
];
export const DC_SIZE_CHROMA: ReadonlyArray<readonly [code: number, bits: number]> = [
{fmt_pairs(list(zip(dcc_code,dcc_bits)))}
];

/** macroblock_type flags */
export const MB_QUANT = 1, MB_FORWARD = 2, MB_BACKWARD = 4, MB_PATTERN = 8, MB_INTRA = 16;

/** Tables B.2a / B.2b / B.2c macroblock_type: [code, bits, flags] */
export const MB_TYPE_I: ReadonlyArray<readonly [number, number, number]> = [[1, 1, MB_INTRA], [1, 2, MB_INTRA | MB_QUANT]];
export const MB_TYPE_P: ReadonlyArray<readonly [number, number, number]> = [
  [1, 1, MB_FORWARD | MB_PATTERN], [1, 2, MB_PATTERN], [1, 3, MB_FORWARD], [3, 5, MB_INTRA],
  [2, 5, MB_QUANT | MB_FORWARD | MB_PATTERN], [1, 5, MB_QUANT | MB_PATTERN], [1, 6, MB_QUANT | MB_INTRA],
];
export const MB_TYPE_B: ReadonlyArray<readonly [number, number, number]> = [
  [2, 2, MB_FORWARD | MB_BACKWARD], [3, 2, MB_FORWARD | MB_BACKWARD | MB_PATTERN], [2, 3, MB_BACKWARD], [3, 3, MB_BACKWARD | MB_PATTERN],
  [2, 4, MB_FORWARD], [3, 4, MB_FORWARD | MB_PATTERN], [3, 5, MB_INTRA], [2, 5, MB_QUANT | MB_FORWARD | MB_BACKWARD | MB_PATTERN],
  [1, 6, MB_QUANT | MB_INTRA], [2, 6, MB_QUANT | MB_BACKWARD | MB_PATTERN], [3, 6, MB_QUANT | MB_FORWARD | MB_PATTERN],
];

/** Default intra quantiser matrix in raster order (the non-intra default is 16 everywhere) */
export const DEFAULT_INTRA_MATRIX: ReadonlyArray<number> = [
{fmt_ints(intra, 8)}
];
'''
open(OUT,'w').write(ts)
print('ok', len(ts))
